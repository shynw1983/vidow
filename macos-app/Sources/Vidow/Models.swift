struct SubtitleTrackOption: Identifiable, Hashable {
    var id: String { "\(isAutoGenerated ? "auto:" : "off:")\(langCode)" }
    let langCode: String
    let displayName: String
    let isAutoGenerated: Bool

    var chipLabel: String {
        let trimmed = displayName.trimmingCharacters(in: .whitespacesAndNewlines)
        let showCode = trimmed.caseInsensitiveCompare(langCode) != .orderedSame &&
            !trimmed.localizedCaseInsensitiveContains(langCode)
        return showCode ? "\(trimmed) (\(langCode))" : trimmed
    }
}

