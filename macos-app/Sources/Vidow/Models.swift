struct LocalVideoInfo {
    let url: URL
    let fileName: String
    let fileSizeBytes: Int64
    let durationSeconds: Double
    let width: Int
    let height: Int
    let frameRate: Double
    let videoCodec: String
    let audioCodec: String?
    let containerExt: String
    let bitrateBps: Int64
    let isHDR: Bool
    let hasAudio: Bool

    var shortSide: Int { min(width, height) }
    var resolutionLabel: String { "\(width)×\(height)" }

    var compatibilityIssues: [String] {
        var issues: [String] = []
        if isHDR {
            issues.append(L10n.t("issue_hdr"))
        }
        let codecLower = videoCodec.lowercased()
        if !codecLower.contains("h264") && !codecLower.contains("avc") && !codecLower.contains("h.264") {
            issues.append(L10n.f("issue_codec", videoCodec.uppercased()))
        }
        if containerExt.lowercased() != "mp4" {
            issues.append(L10n.f("issue_container", containerExt.uppercased()))
        }
        if shortSide > 1080 {
            issues.append(L10n.f("issue_high_res", resolutionLabel))
        }
        if frameRate > 62 {
            issues.append(L10n.f("issue_high_fps", Int(frameRate.rounded())))
        }
        return issues
    }
}

struct ConversionConfig: Equatable {
    var presetId: String = ConversionPreset.universalCompat.rawValue
    var videoCodec: OutputVideoCodec = .h264
    var toneMapHdrToSdr: Bool = true
    var resolutionCap: ResolutionCap = .p1080
    var frameRateCap: FrameRateCap = .fps30
    var aspectRatio: AspectRatioOption = .original
    var aspectFitMode: AspectFitMode = .crop
    var compressionMode: CompressionMode = .quality
    var qualityTier: QualityTier = .balanced
    var targetSizeMb: Int = 25
    var autoDownscaleForTargetSize: Bool = true
    var removeAudio: Bool = false
    var stripMetadata: Bool = true
    var trimStartSeconds: Double = 0
    var trimEndSeconds: Double = 0

    static func forPreset(_ preset: ConversionPreset, duration: Double) -> ConversionConfig {
        var cfg = ConversionConfig(presetId: preset.rawValue, trimStartSeconds: 0, trimEndSeconds: duration)
        switch preset {
        case .universalCompat:
            cfg.videoCodec = .h264
            cfg.toneMapHdrToSdr = true
            cfg.resolutionCap = .p1080
            cfg.frameRateCap = .fps30
            cfg.compressionMode = .quality
            cfg.qualityTier = .high
        case .chatCompact:
            cfg.videoCodec = .h264
            cfg.toneMapHdrToSdr = true
            cfg.resolutionCap = .p720
            cfg.frameRateCap = .fps30
            cfg.compressionMode = .quality
            cfg.qualityTier = .compact
        case .upload25MB:
            cfg.videoCodec = .h264
            cfg.toneMapHdrToSdr = true
            cfg.resolutionCap = .p1080
            cfg.frameRateCap = .fps30
            cfg.compressionMode = .targetSize
            cfg.targetSizeMb = 25
            cfg.autoDownscaleForTargetSize = true
        case .hevcSpaceSaver:
            cfg.videoCodec = .hevc
            cfg.toneMapHdrToSdr = false
            cfg.resolutionCap = .original
            cfg.frameRateCap = .original
            cfg.compressionMode = .quality
            cfg.qualityTier = .balanced
        case .quickTrim:
            cfg.videoCodec = .h264
            cfg.toneMapHdrToSdr = true
            cfg.resolutionCap = .original
            cfg.frameRateCap = .original
            cfg.compressionMode = .quality
            cfg.qualityTier = .high
            cfg.stripMetadata = true
        }
        return cfg
    }
}

