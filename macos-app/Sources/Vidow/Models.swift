struct ParsedLinkInfo {
    let url: String
    let title: String
    let uploader: String
    let durationSeconds: Int
    let extractor: String
    let thumbnailUrl: String?
    let defaultExt: String
    let defaultVideoCodec: String?
    let bestAudioCodec: String
    let bestAudioExt: String
    let bestAudioBitrateKbps: Int
    let bestAudioSizeBytes: Int64?
    let compatQualities: [ParsedQualityOption]
    let bestQualities: [ParsedQualityOption]
    let officialSubtitles: [SubtitleTrackOption]
    let autoSubtitles: [SubtitleTrackOption]

    var hasAnySubtitles: Bool {
        !officialSubtitles.isEmpty || !autoSubtitles.isEmpty
    }

    func qualities(for mode: DownloadFormatMode) -> [ParsedQualityOption] {
        switch mode {
        case .videoMP4: return compatQualities
        case .videoBest: return bestQualities
        case .audioM4A: return []
        }
    }

    func activeQuality(mode: DownloadFormatMode, selectedMaxHeight: Int?) -> ParsedQualityOption? {
        let list = qualities(for: mode)
        guard !list.isEmpty else { return nil }
        guard let maxH = selectedMaxHeight else { return list.first }
        return list.first(where: { $0.ytDlpHeight == maxH })
            ?? list.first(where: { $0.ytDlpHeight <= maxH })
            ?? list.first
    }
}

